"""agentbay.config.yaml: per-project user settings.

    apiVersion: agentbay/v2
    secrets: { provider: env }                  # override env provider (e.g. on Linux)
    approvals: { chat: true }                   # let gates be approved from chat (default off)
    modes:
      feed-briefing:
        lookback: 3d
        maxItemsPerRun: 200
        features:
          digest: { extraRules: rules/digest-extra.yaml }
    connectors:
      x-api: { userId: "12345" }

Capabilities are bound only in envs/<env>.yaml (no override here).

Settings can only tighten: numeric caps take the minimum of mode constraint,
config and env limit.
"""
from __future__ import annotations

from pathlib import Path

import yaml

NAME = "agentbay.config.yaml"
CAPS = ("monthlyItems", "spendUsd", "maxItemsPerRun")
COST_PER_POST_USD = 0.005      # default price per post read (X API pay-per-use); config costPerPostUsd overrides


class ConfigError(Exception):
    pass


def load(project: Path | None) -> dict:
    if project is None:
        return {}
    p = project / NAME
    if not p.exists():
        return {}
    from .model import schema, schema_errors
    doc = yaml.safe_load(p.read_text(encoding="utf-8")) or {}
    errs = schema_errors(doc, schema("config"))
    if errs:
        raise ConfigError(f"{p}:\n    " + "\n    ".join(errs))
    return doc


def chat_approvals(cfg: dict) -> bool:
    """`approvals: { chat: true }`: the owner lets the Chief of Staff relay a gate approval from chat
    (`bay approve --via chat`). Off unless set to exactly true (proposal 0006, Part G)."""
    return (cfg.get("approvals") or {}).get("chat") is True


def config_path(project: Path | None, rel: str) -> Path:
    p = Path(rel)
    if not p.is_absolute() and project is not None:
        p = project / p
    return p


def mode_settings(cfg: dict, mode: str) -> tuple[dict, dict]:
    """(mode settings without 'features', {feature: settings})"""
    m = dict((cfg.get("modes") or {}).get(mode) or {})
    feats = m.pop("features", {}) or {}
    return m, feats


def effective_constraints(mode_constraints: dict, settings: dict) -> dict:
    out = dict(mode_constraints)
    for k in CAPS:
        if k in settings:
            out[k] = min(out[k], settings[k]) if k in out else settings[k]
    return out


def caps(constraints: dict, env_limits: dict, settings: dict) -> dict:
    """Strictest of mode constraints (already merged with config) and env hard limits."""
    out = {}
    for k in CAPS:
        vals = [v for v in (constraints.get(k), env_limits.get(k), settings.get(k)) if v is not None]
        if vals:
            out[k] = min(vals)
    out["costPerPostUsd"] = settings.get("costPerPostUsd", COST_PER_POST_USD)
    return out


# --- `bay config example`: the example config, assembled from each extension's config.example.yaml ----------

EXAMPLE = "agentbay.config.example.yaml"
FRAGMENT = "config.example.yaml"

KERNEL_HEADER = """\
# Copy to <your project>/agentbay.config.yaml. Every setting is optional.
# Settings can only tighten limits: caps take the strictest of mode constraint,
# this file and the env's hard limits.
# Generated by `bay config example` from each extension's config.example.yaml; edit those, not this file.
apiVersion: agentbay/v2

# Where connector secrets come from. keychain (macOS, default) reads
#   security find-generic-password -s agentbay -a <NAME> -w
# env reads environment variables of the same name (use on Linux / CI).
secrets: { provider: keychain }
"""

KERNEL_WORKFLOWS = """\
# Project workflows: your own sequences of endpoints, run by the Chief of Staff (`cos.run`), one stage at a
# time. `call` is a <mode>.<endpoint>; `with`/`when`/$in/$steps work as they do inside a mode's workflow.
# `bay validate` prints each workflow's stages and the effects it may use.
# workflows:
#   morning:
#     description: refresh the feed, then digest it
#     in: { type: object, properties: { lookback: { type: string } } }
#     steps:
#       - { id: sync,   call: feed-briefing.sync,   with: { lookback: "$in.lookback" } }
#       - { id: digest, call: feed-briefing.digest, when: $steps.sync.added }
#       - { id: ship,   gate: "send the digest?" }     # only `bay approve <runId>` passes this
"""

OFFLINE_SWITCH = """\
# Offline switch: each entry runs every agent of an env in the shipped env that substitutes it (fake sources,
# no network, $0). Delete an entry to use the real source. Capabilities stay bound only in envs/<env>.yaml.
"""


def takes_settings(kind: str, doc) -> bool:
    """A mode takes settings when it has a config schema (own or inherited) and is installable (not abstract);
    a connector when it declares `config:`."""
    if kind == "Mode":
        return bool(doc.spec.get("config")) and not doc.spec.get("abstract")
    return bool(doc.spec.get("config"))


def fragment(name: str, text: str) -> str:
    """One extension's example settings, indented under its `<name>:` (all-comment: as a comment block)."""
    lines = [ln.rstrip() for ln in text.strip("\n").splitlines()]
    if all(not ln.strip() or ln.lstrip().startswith("#") for ln in lines):
        body = [f"  #   {ln.lstrip()[1:].lstrip()}" if ln.strip() else "" for ln in lines]
        return "\n".join([f"  # {name}:", *body])
    return "\n".join([f"  {name}:", *[f"    {ln}" if ln else "" for ln in lines]])


def _section(kit, kind: str) -> list[str]:
    docs = kit.docs[kind].values()
    order = sorted(docs, key=lambda d: (d.root != "user", d.name))
    return [fragment(d.name, (d.dir / FRAGMENT).read_text(encoding="utf-8"))
            for d in order if takes_settings(kind, d) and (d.dir / FRAGMENT).exists()]


def example(kit) -> str:
    """The text of agentbay.config.example.yaml for this kit."""
    swaps = {e.spec["substitutes"]: e.name for e in sorted(kit.docs["Environment"].values(), key=lambda e: e.name)
             if e.spec.get("substitutes")}
    parts = [KERNEL_HEADER, "modes:\n" + "\n\n".join(_section(kit, "Mode")) + "\n", KERNEL_WORKFLOWS,
             "connectors:\n" + "\n".join(_section(kit, "Connector")) + "\n"]
    if swaps:
        pairs = ", ".join(f"{k}: {v}" for k, v in sorted(swaps.items()))
        parts.append(OFFLINE_SWITCH + "envs: { " + pairs + " }\n")
    return "\n".join(parts)
